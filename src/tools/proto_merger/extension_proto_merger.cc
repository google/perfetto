struct ImportResult {
  std::unique_ptr<google::protobuf::compiler::DiskSourceTree> source_tree;
  std::unique_ptr<protozero::MultiFileErrorCollectorImpl> error_collector;
  std::unique_ptr<google::protobuf::compiler::Importer> importer;
  const google::protobuf::FileDescriptor* file_descriptor;
};

ImportResult ImportProto(const std::string& proto_file,
                         const std::string& proto_dir_path) {
  auto dst = std::make_unique<google::protobuf::compiler::DiskSourceTree>();
  dst->MapPath("", proto_dir_path);
  dst->MapPath("", ".");
  dst->MapPath("", "buildtools/protobuf/src");

  auto mfe = std::make_unique<protozero::MultiFileErrorCollectorImpl>();

  ImportResult result;
  result.importer = std::make_unique<google::protobuf::compiler::Importer>(
      dst.get(), mfe.get());
  result.source_tree = std::move(dst);
  result.error_collector = std::move(mfe);
  result.file_descriptor = result.importer->Import(proto_file);
  return result;
}

// Recursively collects all extension files and their helper dependencies,
// skipping standard base Perfetto protos, google protobuf descriptors,
// and the input base proto itself.
void CollectExtensionFiles(
    const google::protobuf::FileDescriptor* file,
    const google::protobuf::FileDescriptor* input_desc,
    std::unordered_set<const google::protobuf::FileDescriptor*>& visited,
    std::vector<const google::protobuf::FileDescriptor*>& out) {
  if (!file || file == input_desc || !visited.insert(file).second) {
    return;
  }

  std::string name(file->name());
  if (base::StartsWith(name, "protos/perfetto/") ||
      base::StartsWith(name, "google/protobuf/") ||
      (input_desc && name == input_desc->name())) {
    return;
  }

  for (int i = 0; i < file->dependency_count(); ++i) {
    CollectExtensionFiles(file->dependency(i), input_desc, visited, out);
  }

  out.push_back(file);
}

