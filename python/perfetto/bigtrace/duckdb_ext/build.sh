#!/bin/bash
# Builds perfetto.duckdb_extension (DuckDB C extension API, C_STRUCT ABI) for
# DuckDB v1.5.6. SQL macros in sql/*.sql are embedded into the binary;
# statements in a file are separated by a line containing only "-- @@".
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p generated
python3 - <<'PY'
import glob
stmts = []
for f in sorted(glob.glob('sql/*.sql')):
    text = open(f).read()
    for s in text.split('\n-- @@\n'):
        if s.strip() and not all(l.strip().startswith('--') or not l.strip() for l in s.splitlines()):
            stmts.append(s.strip())
def cstr(s):
    return 'R"PERFETTOSQL(' + s + ')PERFETTOSQL"'
with open('generated/sql_macros.h', 'w') as o:
    o.write('// Generated by build.sh from sql/*.sql. Do not edit.\n#pragma once\n')
    o.write('static const char* const kSqlMacros[] = {\n')
    for s in stmts: o.write('  ' + cstr(s) + ',\n')
    o.write('};\n')
PY
CXXFLAGS="-O3 -march=native -std=c++17 -fPIC -fvisibility=hidden -pthread \
  -Wall -Wextra -Wno-missing-field-initializers -Isrc -I."
mkdir -p generated/obj
pids=()
for f in src/*.cc; do
  g++ $CXXFLAGS -c "$f" -o "generated/obj/$(basename "${f%.cc}").o" & pids+=($!)
done
for p in "${pids[@]}"; do wait "$p"; done
g++ -shared -static-libstdc++ -static-libgcc -pthread generated/obj/*.o \
  -o libperfetto.so.tmp
mv -f libperfetto.so.tmp libperfetto.so
python3 package_extension.py --library libperfetto.so \
  --out perfetto.duckdb_extension.tmp --platform linux_amd64 \
  --duckdb-version v1.5.6 --abi-type C_STRUCT
mv -f perfetto.duckdb_extension.tmp perfetto.duckdb_extension
echo "built $(pwd)/perfetto.duckdb_extension"
