# input_video.textproto: display 0 video frames 1-9 (portrait, then rotated
# to landscape from frame 4; frame 5 has no source size and no vsync link).
# - A tap: DOWN 0x1001 is answered exactly by frame 3; UP 0x1002 by frame 5,
#   the next frame by present time, which beats the next frame by vsync id.
# - A two-finger gesture on the rotated display, without atrace.
# - DOWN 0x5001 at the same ts as frame 7, with its axes in reverse order,
#   answered by an app frame with two layers; frame 8, the next frame by vsync
#   id, beats the next frame by present time.
# - An injected DOWN 0xc0009001 (IdGenerator::Source::OTHER, e.g. UiAutomator),
#   with no InputReader notifyMotion slice, answered exactly by frame 9.
# - A touch split by InputDispatcher (0x7001, copy 0x40007002), with an
#   OUTSIDE copy (0x40007003), and a CANCEL (0x40007004) and a DOWN
#   (0x40007005) generated by InputDispatcher.
# - DOWN 0x8001 and POINTER_DOWN 0x8002 in the same input frame, with a split
#   copy (0x40008003) of the POINTER_DOWN.
# - A redacted DOWN and a DOWN on a display without video.
