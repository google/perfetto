  # Injected input events (IdGenerator::Source::OTHER = 3, e.g. UiAutomator)
  # bypass InputReader, so read_time and end_to_end_latency_dur stay NULL, while
  # event_action and frame_id are still resolved from InputDispatcher + app
  # delivery slices.
  def test_android_input_events_injected(self):
    return DiffTestBlueprint(
        trace=Path('input_video.textproto'),
        query="""
        INCLUDE PERFETTO MODULE android.input;
        SELECT
          input_event_id,
          event_action,
          read_time,
          end_to_end_latency_dur,
          frame_id,
          is_speculative_frame,
          frame_event_time
        FROM android_input_events
        WHERE input_event_id IN ('0x1001', '0xc0009001')
          AND process_name = 'com.example.app'
        ORDER BY dispatch_ts;
        """,
        out=Csv("""
        "input_event_id","event_action","read_time","end_to_end_latency_dur","frame_id","is_speculative_frame","frame_event_time"
        "0x1001","DOWN",100100000,24900000,5001,1,100100000
        "0xc0009001","DOWN","[NULL]","[NULL]",5020,1,229000000
        """))
